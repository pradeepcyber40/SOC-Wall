class PortInventory(Base):
    __tablename__ = "port_inventory"
    
    id = Column(Integer, primary_key=True, index=True)
    asset_id = Column(String(64), ForeignKey("assets.asset_id", ondelete="CASCADE"), nullable=False, index=True)
