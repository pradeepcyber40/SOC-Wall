class SecurityAlert(Base):
    __tablename__ = "security_alerts"
    
    alert_id = Column(String(64), primary_key=True, index=True)
    severity = Column(String(20), index=True, nullable=False) # 'Critical', 'High', 'Medium', 'Low', 'Informational'
    asset_id = Column(String(64), ForeignKey("assets.asset_id", ondelete="SET NULL"), nullable=True, index=True)
    asset_hostname = Column(String(128), nullable=False)
    source = Column(String(32), default="Wazuh", nullable=False)
    alert_type = Column(String(128), nullable=False)
    description = Column(Text, nullable=False)
    raw_payload = Column(JSON)
    status = Column(String(32), default="New", index=True, nullable=False) # 'New', 'Investigating', 'Acknowledged', 'Resolved'
    assigned_analyst = Column(String(64), default="Unassigned")
    created_at = Column(DateTime, default=datetime.utcnow, index=True)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    asset = relationship("Asset", back_populates="alerts")

class AuditLog(Base):
    __tablename__ = "audit_logs"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    username = Column(String(64), index=True, nullable=False)
    action = Column(String(128), index=True, nullable=False)
    resource = Column(String(128), nullable=False)
    ip = Column(String(45), default="127.0.0.1")
    result = Column(String(32), default="Success", nullable=False) # 'Success', 'Failed', 'Denied'
    details = Column(Text)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)

class AgentMetric(Base):
    __tablename__ = "agent_metrics"
    
    id = Column(Integer, primary_key=True, index=True)
    agent_id = Column(String(64), ForeignKey("agents.agent_id", ondelete="CASCADE"), nullable=False, index=True)
    bytes_uploaded = Column(BigInteger, default=0)
    bytes_downloaded = Column(BigInteger, default=0)
    discovery_packets = Column(BigInteger, default=0)
    scan_duration_ms = Column(BigInteger, default=0)
    api_requests_count = Column(Integer, default=0)
