from datetime import datetime
from sqlalchemy import (
    Column, Integer, String, Boolean, DateTime, Float, ForeignKey, Text, BigInteger, JSON
)
from sqlalchemy.orm import relationship
from app.database import Base

class User(Base):
    __tablename__ = "users"
    
    id = Column(Integer, primary_key=True, index=True)
    username = Column(String(64), unique=True, index=True, nullable=False)
    email = Column(String(128), unique=True, index=True, nullable=False)
    full_name = Column(String(128), nullable=False)
    hashed_password = Column(String(256), nullable=False)
    role = Column(String(32), default="SOC Analyst", nullable=False) # 'Super Admin', 'SOC Admin', 'SOC Analyst', 'Viewer'
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

class Agent(Base):
    __tablename__ = "agents"
    
    agent_id = Column(String(64), primary_key=True, index=True) # Stable UUID generated by EXE
    hostname = Column(String(128), index=True, nullable=False)
    computer_name = Column(String(128))
    os_version = Column(String(128))
    os_build = Column(String(64))
    os_arch = Column(String(32))
    current_ip = Column(String(45), index=True, nullable=False)
    mac_address = Column(String(32), nullable=False)
    agent_version = Column(String(32), default="1.0.0", nullable=False)
    status = Column(String(20), default="ONLINE", index=True, nullable=False) # ONLINE, OFFLINE, WARNING
    config_version = Column(Integer, default=1, nullable=False)
    auth_token = Column(String(256), nullable=False)
    cpu_model = Column(String(128))
    cpu_cores = Column(Integer)
    ram_total_mb = Column(BigInteger)
    disk_total_gb = Column(BigInteger)
    uptime_sec = Column(BigInteger)
    first_seen = Column(DateTime, default=datetime.utcnow)
    last_seen = Column(DateTime, default=datetime.utcnow, index=True)
    last_heartbeat = Column(DateTime, default=datetime.utcnow)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    heartbeats = relationship("AgentHeartbeat", back_populates="agent", cascade="all, delete-orphan")
    assets = relationship("Asset", back_populates="agent")

class Asset(Base):
    __tablename__ = "assets"
    
    asset_id = Column(String(64), primary_key=True, index=True)
    agent_id = Column(String(64), ForeignKey("agents.agent_id", ondelete="SET NULL"), nullable=True, index=True)
    hostname = Column(String(128), index=True, nullable=False)
    ip_address = Column(String(45), index=True, nullable=False)
    mac_address = Column(String(32), index=True, nullable=False)
    category = Column(String(32), index=True, default="Unknown", nullable=False)
    # Categories: Computer, Laptop, Server, Mobile, Router, Switch, Firewall, Printer, Camera, Access Point, IoT, Other, Unknown
    manufacturer = Column(String(64), default="Unknown")
    model = Column(String(128), default="Unknown")
    os = Column(String(128), default="Unknown")
    status = Column(String(20), default="ONLINE", index=True, nullable=False) # ONLINE, OFFLINE, UNKNOWN, WARNING
    risk = Column(String(20), default="None", index=True, nullable=False) # Critical, High, Medium, Low, None
    classification_confidence = Column(Float, default=0.0)
    subnet = Column(String(45), index=True)
    vlan = Column(String(32))
    network_vendor = Column(String(64))
    is_managed = Column(Boolean, default=False) # True if running RasiSOC-Agent.exe
    discovery_method = Column(String(64), default="Agent Probe")
    first_seen = Column(DateTime, default=datetime.utcnow)
    last_seen = Column(DateTime, default=datetime.utcnow, index=True)
    last_heartbeat = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    agent = relationship("Agent", back_populates="assets")
    interfaces = relationship("NetworkInterface", back_populates="asset", cascade="all, delete-orphan")
    software = relationship("SoftwareInventory", back_populates="asset", cascade="all, delete-orphan")
    services = relationship("ServiceInventory", back_populates="asset", cascade="all, delete-orphan")
    ports = relationship("PortInventory", back_populates="asset", cascade="all, delete-orphan")
    alerts = relationship("SecurityAlert", back_populates="asset", cascade="all, delete-orphan")

class NetworkInterface(Base):
    __tablename__ = "network_interfaces"
    
    id = Column(Integer, primary_key=True, index=True)
    asset_id = Column(String(64), ForeignKey("assets.asset_id", ondelete="CASCADE"), nullable=False, index=True)
    agent_id = Column(String(64), nullable=True)
    interface_name = Column(String(128), nullable=False)
    ip_address = Column(String(45), index=True)
    mac_address = Column(String(32))
    gateway = Column(String(45))
    subnet = Column(String(45))
    vlan = Column(String(32))
    is_up = Column(Boolean, default=True)
    speed_mbps = Column(BigInteger)
    vendor = Column(String(64))
    created_at = Column(DateTime, default=datetime.utcnow)

    asset = relationship("Asset", back_populates="interfaces")

class AssetDiscovery(Base):
    __tablename__ = "asset_discovery"
    
    id = Column(Integer, primary_key=True, index=True)
    agent_id = Column(String(64), ForeignKey("agents.agent_id", ondelete="CASCADE"), nullable=False, index=True)
    asset_id = Column(String(64), ForeignKey("assets.asset_id", ondelete="SET NULL"), nullable=True)
    target_subnet = Column(String(45), nullable=False)
