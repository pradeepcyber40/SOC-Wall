class AgentHeartbeat(Base):
    __tablename__ = "agent_heartbeats"
    
    id = Column(Integer, primary_key=True, index=True)
    agent_id = Column(String(64), ForeignKey("agents.agent_id", ondelete="CASCADE"), nullable=False, index=True)
    cpu_usage_pct = Column(Float)
    ram_usage_pct = Column(Float)
    disk_usage_pct = Column(Float)
    uptime_sec = Column(BigInteger)
    payload_bytes = Column(Integer, default=0)
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    agent = relationship("Agent", back_populates="heartbeats")

